/* bake_font.c - bake an antialiased monospace face into 1-bit-safe C tables.
 *
 * The iDBox has no freetype, so the LCD builds with a pre-rendered 8-bit alpha
 * atlas. Text is monospace (fixed cell), which keeps fbdash's layout math.
 *
 *   gcc -O2 -o bake_font bake_font.c $(pkg-config --cflags --libs freetype2)
 *   ./bake_font /path/font.ttf 11 13 16 22 > font_aa.h
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <ft2build.h>
#include FT_FREETYPE_H
#include FT_GLYPH_H

#define FIRST 32
#define LAST 176          /* 32..176 covers Latin-1 basics incl. the degree sign */
#define NGLYPHS (LAST - FIRST + 1)

int main(int argc, char **argv) {
    if (argc < 3) {
        fprintf(stderr, "usage: %s [--prefix P] [--fixed] font.ttf px...\n", argv[0]);
        return 1;
    }
    FT_Library lib;
    if (FT_Init_FreeType(&lib)) return 1;
    FT_Face face;
    const char *prefix = "";
    int fixed_cell = 0;
    int sizes[8], ns = 0, ai = 1;
    for (; ai < argc; ai++) {
        if (!strcmp(argv[ai], "--prefix") && ai + 1 < argc) { prefix = argv[++ai]; continue; }
        if (!strcmp(argv[ai], "--fixed")) { fixed_cell = 1; continue; }
        break;
    }
    const char *fontfile = argv[ai++];
    if (FT_New_Face(lib, fontfile, 0, &face)) {
        fprintf(stderr, "cannot open %s\n", fontfile);
        return 1;
    }
    for (; ai < argc && ns < 8; ai++) sizes[ns++] = atoi(argv[ai]);

    printf("/* generated by bake_font.c from %s - do not edit */\n", strrchr(fontfile, '/') + 1);
    printf("#pragma once\n\n");
    printf("#ifndef AA_FACE_DEF\n#define AA_FACE_DEF\n");
    printf("struct aa_glyph { signed char xoff; signed char yoff; unsigned char w, h; unsigned short adv; unsigned int off; };\n");
    printf("struct aa_face { int px, cellw, ascent, lineh, caph; const struct aa_glyph *g; const unsigned char *bm; };\n");
    printf("#endif\n\n");

    for (int s = 0; s < ns; s++) {
        int px = sizes[s];
        FT_Set_Pixel_Sizes(face, 0, px);
        /* cell width from 'M' advance */
        FT_UInt gi = FT_Get_Char_Index(face, fixed_cell ? '0' : 'M');
        FT_Load_Glyph(face, gi, FT_LOAD_DEFAULT);
        int cellw = (int)((face->glyph->advance.x + 32) >> 6);
        if (fixed_cell) cellw += 1;                 /* tabular: every digit same width */
        if (cellw < 1) cellw = px / 2;

        /* measure */
        int ascent = (int)((face->size->metrics.ascender + 32) >> 6);
        int lineh = (int)((face->size->metrics.height + 32) >> 6);
        unsigned int total = 0, maxw = 0, maxh = 0;
        for (int c = FIRST; c <= LAST; c++) {
            FT_UInt g = FT_Get_Char_Index(face, c);
            if (!g) continue;
            FT_Load_Glyph(face, g, FT_LOAD_RENDER | FT_LOAD_TARGET_LIGHT);
            FT_GlyphSlot sl = face->glyph;
            total += sl->bitmap.rows * sl->bitmap.width;
            if (sl->bitmap.width > maxw) maxw = sl->bitmap.width;
            if (sl->bitmap.rows > maxh) maxh = sl->bitmap.rows;
        }

        printf("/* ---- %d px, cell %d, ascent %d, line %d ---- */\n", px, cellw, ascent, lineh);
        unsigned char *bm = calloc(total + 8, 1);
        unsigned int off = 0;
        printf("static const unsigned char AA_BM_%s%d[] = {\n", prefix, px);
        for (int c = FIRST; c <= LAST; c++) {
            FT_UInt g = FT_Get_Char_Index(face, c);
            if (!g) continue;
            FT_Load_Glyph(face, g, FT_LOAD_RENDER | FT_LOAD_TARGET_LIGHT);
            FT_GlyphSlot sl = face->glyph;
            int w = sl->bitmap.width, h = sl->bitmap.rows;
            for (int y = 0; y < h; y++) {
                for (int x = 0; x < w; x++) bm[off++] = sl->bitmap.buffer[y * sl->bitmap.pitch + x];
            }
        }
        /* emit as decimal bytes, 24 per line */
        for (unsigned int i = 0; i < off; i++) {
            if (i % 24 == 0) printf("  ");
            printf("%u,", bm[i]);
            if (i % 24 == 23) printf("\n");
        }
        printf("\n};\n");

        printf("static const struct aa_glyph AA_G_%s%d[] = {\n", prefix, px);
        off = 0;
        for (int c = FIRST; c <= LAST; c++) {
            FT_UInt g = FT_Get_Char_Index(face, c);
            if (!g) { printf("  {0,0,0,0,%d,0},\n", cellw); continue; }
            FT_Load_Glyph(face, g, FT_LOAD_RENDER | FT_LOAD_TARGET_LIGHT);
            FT_GlyphSlot sl = face->glyph;
            int w = sl->bitmap.width, h = sl->bitmap.rows;
            printf("  {%d,%d,%d,%d,%d,%u},\n", sl->bitmap_left, sl->bitmap_top, w, h, cellw, off);
            off += (unsigned int)(w * h);
        }
        printf("};\n");
        FT_UInt hg = FT_Get_Char_Index(face, 'H');
        FT_Load_Glyph(face, hg, FT_LOAD_RENDER | FT_LOAD_TARGET_LIGHT);
        int caph = face->glyph->bitmap_top;
        printf("static const struct aa_face AA_FACE_%s%d = { %d, %d, %d, %d, %d, AA_G_%s%d, AA_BM_%s%d };\n\n",
               prefix, px, px, cellw, ascent, lineh, caph, prefix, px, prefix, px);
        free(bm);
    }
    return 0;
}
